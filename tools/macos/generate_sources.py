#!/usr/bin/env python3
"""[Blur2PC][macOS] Derive original engine sources from authoritative Jam rules."""
import argparse
from datetime import datetime, timezone
import getpass
import os
import platform
import json
from pathlib import Path
import subprocess
import sys


def actual_path(root, relative):
    current = root
    for component in Path(relative).parts:
        matches = [p for p in current.iterdir() if p.name.casefold() == component.casefold()]
        if len(matches) != 1:
            raise ValueError(f"Missing or ambiguous source path: {relative}")
        current = matches[0]
    return current.relative_to(root).as_posix()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--top', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    root = args.top.resolve()
    output = args.out.resolve()
    output.mkdir(parents=True, exist_ok=True)
    manifest = output / 'targets_pc_speed.json'
    subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'),
                    '--top', str(root), '--root', 'code/amax/game/jamfile.jam',
                    '--target', 'WIN32', '--platform', 'PC', '--build', 'Speed',
                    '--out', str(manifest)], check=True, cwd=root)
    # Real local build metadata for the original BuildStamp API. SOURCE_DATE_EPOCH
    # supports reproducible builds; generated data stays in ignored build output.
    epoch = int(os.environ['SOURCE_DATE_EPOCH']) if 'SOURCE_DATE_EPOCH' in os.environ else None
    built = datetime.fromtimestamp(epoch, timezone.utc) if epoch is not None else datetime.now(timezone.utc)
    revision = subprocess.check_output(['git', 'rev-parse', '--short=12', 'HEAD'], cwd=root, text=True).strip()
    dirty = subprocess.run(['git', 'diff', '--quiet', 'HEAD'], cwd=root).returncode
    untracked = subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], cwd=root, text=True)
    if dirty or untracked: revision += '-dirty'
    stamp = [built.strftime('%H:%M:%S UTC'), built.strftime('%Y-%m-%d'), getpass.getuser(),
             platform.node(), 'native-development', 'Change', revision]
    (output / 'NativeBuildStampData.h').write_text(
        '// Generated native local build information.\n#pragma once\n' +
        'static const char* const nativeBuildStampFields[] = {\n' +
        ''.join('    ' + json.dumps(value) + ',\n' for value in stamp) + '};\n')
    description=json.loads(manifest.read_text())
    targets=description['targets']
    # Bundle the exact original Jam scripts with physical path casing.
    native_lua=dict(description)
    native_lua['lua_bundles']=[dict(bundle,root=actual_path(root,bundle['root']),
        scripts=[actual_path(root,p) for p in bundle['scripts']]) for bundle in description['lua_bundles']]
    (output/'lua_macos.json').write_text(json.dumps(native_lua,indent=2)+'\n')
    lua_target = next(t for t in targets if t['name'] == 'liblua')
    lua_include = str(Path(actual_path(root,lua_target['sources'][0])).parent)
    compression=[actual_path(root,p) for t in targets if t['name']=='zlib' for p in t['sources'] if p.lower().endswith('/compression.cpp')]
    compression=list(dict.fromkeys(compression))
    core = next(t for t in targets if t['name'] == 'core')
    # These Windows/console implementations are replaced by NativeThreads.cpp.
    replacements = {'event.cpp', 'mutex.cpp', 'rwlock.cpp', 'semaphore.cpp', 'thread.cpp'}
    sources, replaced = [], []
    for relative in core['sources']:
        actual = actual_path(root, relative)
        if '/threads/' in actual and Path(actual).name.lower() in replacements:
            replaced.append(actual)
        else:
            sources.append(actual)
    core_manifest=output / 'core_macos_speed.json'
    subprocess.run([sys.executable,str(root / 'tools/jam2cmake/jamextract.py'),'--top',str(root),'--root',
        'code/mercury/library/common/core/jamfile.jam','--target','MACOS','--platform','MACOS','--build','Speed','--out',str(core_manifest)],check=True,cwd=root)
    core_mac=next(t for t in json.loads(core_manifest.read_text())['targets'] if t['name']=='core')
    native_core=[actual_path(root,p) for p in core_mac['sources'] if '/macos/' in p.lower()]
    lines = ['# Generated by tools/macos/generate_sources.py; do not edit.',
             'set(BLUR_MAC_CORE_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in sources]
    lines += [')', '']
    lines += ['set(BLUR_MAC_UI_COMPRESSION_SOURCES',*[f'    "${{BLUR_TOP}}/{p}"' for p in compression],')','']
    lines += ['set(BLUR_MAC_CORE_NATIVE_SOURCES',*[f'    "${{BLUR_TOP}}/{p}"' for p in native_core],')','']
    system = next(t for t in targets if t['name'] == 'system')
    selected = {'time/time.cpp', 'network/address.cpp', 'network/socket.cpp',
                'serialise/filepath.cpp', 'serialise/c_filesystem.cpp', 'serialise/i_filesystem.cpp',
                'serialise/filesystemglobals.cpp', 'misc/btlstringutil.cpp', 'memory/blockallocator.cpp', 'memory/virtualmemory.cpp',
                'artery/arterysync.cpp', 'artery/artery.cpp', 'artery/arterymessage.cpp',
                'artery/arterypeer.cpp', 'artery/arteryservice.cpp',
                'io/async.cpp', 'io/asyncfile.cpp', 'io/iodevice.cpp',
                'io/iofile.cpp', 'io/iorequest.cpp', 'io/ioservice.cpp', 'scheduler/jobqueue.cpp', 'scheduler/jobqueue_kernel.cpp',
                'scheduler/jobqueue_mem.cpp', 'scheduler/jobqueue_xenon.cpp',
                'scheduler/jobqueue_task_queue_lf.cpp', 'scheduler/cache.cpp'}
    system_sources = [actual_path(root, p) for p in system['sources']
                      if any(p.lower().endswith('/' + item) for item in selected)]
    if len(system_sources) != len(selected):
        raise ValueError('Expected platform source files missing from system Jam target')
    # Artery's BSD implementation is selected by PS3SRC in the authoritative
    # Jam file. Extract that branch rather than maintaining a native source list.
    bsd_manifest = output / 'system_ps3_speed.json'
    subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'),
                    '--top', str(root), '--root',
                    'code/mercury/library/common/system/jamfile.jam',
                    '--target', 'PS3', '--platform', 'PS3', '--build', 'Speed',
                    '--out', str(bsd_manifest)], check=True, cwd=root)
    bsd_system = next(t for t in json.loads(bsd_manifest.read_text())['targets']
                      if t['name'] == 'system')
    bsd_sockets = [actual_path(root, p) for p in bsd_system['sources']
                   if p.lower().endswith('/artery/bksocket.cpp')]
    if len(bsd_sockets) != 1:
        raise ValueError('Expected original BSD Artery source missing from Jam')
    system_sources += bsd_sockets
    lines += ['set(BLUR_MAC_SYSTEM_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in system_sources]
    lines += [')', '']
    system_includes = list(dict.fromkeys(actual_path(root, p['path'])
                          for p in system['includes'] if p['exists']))
    # Keep a wider engine target for every remaining system object. Its integration
    # executable force-loads all objects so unresolved dependencies remain visible.
    replaced_system = {'serialise/c_file.cpp', 'artery/wssocket.cpp'}
    pending_system = [actual_path(root, p) for p in system['sources']
                      if actual_path(root, p) not in system_sources and
                      not any(p.lower().endswith('/' + item) for item in replaced_system)]
    lines += ['set(BLUR_MAC_ENGINE_SYSTEM_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in pending_system]
    lines += [')', '']
    misc = next(t for t in targets if t['name'] == 'misc_shared')
    message_debug = [actual_path(root, p) for p in misc['sources']
                     if p.lower().endswith('/messaging/messagedebug.cpp')]
    if len(message_debug) != 1:
        raise ValueError('Expected original messaging debug source missing from Jam')
    lines += ['set(BLUR_MAC_MESSAGE_DEBUG_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in message_debug]
    lines += [')', '']
    lines += ['set(BLUR_MAC_SYSTEM_INCLUDE_DIRS']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in system_includes]
    lines += [')', '']
    native_modules = {}
    for name in ('xtgame', 'logicalfs', 'resource', 'framework', 'input', 'display', 'camera2', 'render', 'world_render', 'renderingdata', 'scenegraph', 'fx', 'misc_shared', 'animation', 'air', 'portal', 'shader', 'textureresource', 'game_resource', 'gravity', 'racingphysics', 'dynamic', 'crowd_system', 'effect', 'actor_system', 'animated_model', 'game_context', 'lod', 'resource_utils', 'ui', 'liblua', 'lua_shared', 'lua_helper', 'deferred', 'amax', 'amax_ui', 'amax_gamelogic', 'amax_network', 'network', 'amax_audio', 'amax_racebook', 'amax_kanzen', 'movie', 'navmesh', 'vehicle', 'debugsystems', 'game_debug', 'game_physics', 'gameview', 'helper_screens', 'shared_actors', 'specialfx', 'blobshadows', 'dropshadows', 'auxflares', 'lighttrails', 'splashcamera', 'actor_studio_msg_game', 'actor_studio_msg_shared', 'jpeghelper', 'security', 'advertising'):
        target = next(t for t in targets if t['name'].casefold() == name.casefold())
        module_sources = [actual_path(root, source) for source in target['sources']]
        pending_sources = []
        if name == 'amax':
            game_manifest=output/'game_macos_speed.json'
            subprocess.run([sys.executable,str(root/'tools/jam2cmake/jamextract.py'),'--top',str(root),
                '--root','code/amax/game/jamfile.jam','--target','MACOS','--platform','MACOS',
                '--build','Speed','--out',str(game_manifest)],check=True,cwd=root)
            game_mac=next(t for t in json.loads(game_manifest.read_text())['targets'] if t['name']=='Amax')
            game_main=[actual_path(root,p) for p in game_mac['sources'] if '/macos/' in p.lower()]
            if len(game_main)!=1:raise ValueError('Expected one actual native game entry in Jam')
            lines += ['set(BLUR_MAC_GAME_MAIN_SOURCES',*[f'    "${{BLUR_TOP}}/{p}"' for p in game_main],')','']
        if name == 'movie':
            movie_manifest=output/'movie_macos_speed.json'
            subprocess.run([sys.executable,str(root/'tools/jam2cmake/jamextract.py'),'--top',str(root),
                '--root','code/mercury/library/graphics/movie/jamfile.jam','--target','MACOS','--platform','MACOS',
                '--build','Speed','--out',str(movie_manifest)],check=True,cwd=root)
            native_movie=next(t for t in json.loads(movie_manifest.read_text())['targets'] if t['name']=='movie')
            pending_sources=[p for p in module_sources if '/w32/' in p.lower()]
            module_sources=[actual_path(root,p) for p in native_movie['sources']]
        if name == 'ui':
            ui_manifest=output/'ui_macos_speed.json'
            subprocess.run([sys.executable,str(root/'tools/jam2cmake/jamextract.py'),'--top',str(root),
                '--root','code/mercury/library/ui/jamfile.jam','--target','MACOS','--platform','MACOS',
                '--build','Speed','--out',str(ui_manifest)],check=True,cwd=root)
            ui_mac=next(t for t in json.loads(ui_manifest.read_text())['targets'] if t['name']=='ui')
            module_sources += [actual_path(root,p) for p in ui_mac['sources'] if '/macos/' in p.lower()]
        if name == 'misc_shared':
            # Messaging debug already belongs to the force-linked system closure.
            module_sources = [p for p in module_sources if p not in message_debug]
        if name == 'display':
            shared_display = {'displaytodisplay2.cpp','devicebase.cpp','view.cpp','viewfrustum.cpp','viewport.cpp','viewsettings.cpp','viewsetup.cpp','renderer.cpp','debuglog.cpp','globals.cpp','texture.cpp','textureparams.cpp','vertexformat.cpp','device.cpp','memorytracker.cpp','devicecontext.cpp','context_base.cpp','dynamicvertexbuffer.cpp','basicrender.cpp','vertexshaderutils.cpp','pixelshaderutils.cpp','file.cpp','render.cpp','vertexdeclarations.cpp','vertexshaders.cpp','pixelshaders.cpp','manager.cpp','managerbase.cpp','windowbase.cpp'}
            pending_sources = [p for p in module_sources if Path(p).name.lower() not in shared_display]
            module_sources = [p for p in module_sources if Path(p).name.lower() in shared_display]
            application_display_names = {'devicedebug.cpp','gputiming.cpp','debugrender.cpp','fontrender.cpp',
                'heaprender.cpp','memoryrender.cpp','menurender.cpp','resourcerender.cpp','systemrender.cpp',
                'texturerender.cpp','timingrender.cpp','commandbufferrender.cpp','texture2dutils.cpp',
                'occlusionquery.cpp','textureutils.cpp','ddstextureutils.cpp','tgatextureutils.cpp','bmptextureutils.cpp','surfaceutils.cpp',
                'texture3dutils.cpp','texturecubeutils.cpp','resourcebundlesingle.cpp','resourcebundlereader.cpp',
                'resourcebundlereaderimpl1.cpp','resourcebundlereaderimpl2.cpp','resourcebundlereaderimpl3.cpp'}
            application_display = [p for p in pending_sources if Path(p).name.lower() in application_display_names]
            if len(application_display)!=len(application_display_names):
                raise ValueError('Expected original application display helpers missing from Jam')
            lines += ['set(BLUR_MAC_DISPLAY_APPLICATION_SOURCES']
            lines += [f'    "${{BLUR_TOP}}/{p}"' for p in application_display]
            lines += [')', '']
            display_manifest = output / 'display_macos_speed.json'
            subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'), '--top', str(root),
                '--root', 'code/mercury/library/graphics/display/jamfile.jam', '--target', 'MACOS', '--platform', 'MACOS',
                '--build', 'Speed', '--out', str(display_manifest)], check=True, cwd=root)
            native_display = next(t for t in json.loads(display_manifest.read_text())['targets'] if t['name']=='display')
            module_sources += [actual_path(root,p) for p in native_display['sources'] if '/metal/' in p.lower()]
        if name == 'world_render':
            world_manifest = output / 'world_render_macos_speed.json'
            subprocess.run([sys.executable,str(root / 'tools/jam2cmake/jamextract.py'),'--top',str(root),
                '--root','code/mercury/library/graphics/world_render/jamfile.jam','--target','MACOS','--platform','MACOS',
                '--build','Speed','--out',str(world_manifest)],check=True,cwd=root)
            world_mac = next(t for t in json.loads(world_manifest.read_text())['targets'] if t['name']=='world_render')
            module_sources += [actual_path(root,p) for p in world_mac['sources'] if p.lower().endswith('/modelinterpolation.cpp')]

        if name == 'input':
            shared_input = {'device.cpp','devicemanager.cpp','gameinputmapping.cpp','gameinput.cpp','input.cpp','padvirtual.cpp'}
            pending_sources = [p for p in module_sources if Path(p).name.lower() not in shared_input]
            module_sources = [p for p in module_sources if Path(p).name.lower() in shared_input]
            input_manifest = output / 'input_macos_speed.json'
            subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'), '--top', str(root),
                '--root', 'code/mercury/library/util/input/jamfile.jam', '--target', 'MACOS', '--platform', 'MACOS',
                '--build', 'Speed', '--out', str(input_manifest)], check=True, cwd=root)
            native_input = next(t for t in json.loads(input_manifest.read_text())['targets'] if t['name']=='input')
            module_sources += [actual_path(root,p) for p in native_input['sources'] if '/macos/' in p.lower()]

        if name == 'framework':
            # These original framework services need no graphics backend. Keep
            # the other Jam entries visible as pending instead of stubbing them.
            selected_framework = {'timer.cpp', 'loaddebugvars.cpp', 'framework.cpp', 'applicationparams.cpp',
                                  'layer.cpp', 'layermanager.cpp', 'coresystems.cpp'}
            pending_sources = [p for p in module_sources if Path(p).name.lower() not in selected_framework]
            module_sources = [p for p in module_sources if Path(p).name.lower() in selected_framework]
            if len(module_sources) != len(selected_framework):
                raise ValueError('Expected original framework services missing from Jam')
            # Compile original application bodies separately until the native host
            # and remaining renderer dependencies can link. Never silently drop
            # unresolved services or count this archive as a running application.
            application_sources = [p for p in pending_sources if Path(p).name.lower() != 'applicationpc.cpp']
            lines += ['set(BLUR_MAC_FRAMEWORK_APPLICATION_SOURCES']
            lines += [f'    "${{BLUR_TOP}}/{p}"' for p in application_sources]
            lines += [')', '']
        module_includes, unresolved = [], []
        for entry in target['includes']:
            try:
                # Match the interpreter actually selected by Jam; current/src is a separate older ABI.
                include_path=lua_include if entry['path'].lower()=='code/vendor/lua/current/src' else entry['path']
                resolved = actual_path(root, include_path)
                if resolved not in module_includes: module_includes.append(resolved)
            except ValueError:
                unresolved.append(entry['path'])
        prefix = 'BLUR_MAC_' + name.upper()
        for suffix, values in [('SOURCES', module_sources), ('INCLUDE_DIRS', module_includes)]:
            lines += ['set(' + prefix + '_' + suffix]
            lines += [f'    "${{BLUR_TOP}}/{item}"' for item in values]
            lines += [')', '']
        lines += ['set(' + prefix + '_DEFINES']
        lines += ['    "' + item + '"' for item in target['defines']]
        lines += [')', '']
        lines += ['set(' + prefix + '_ROOT "${BLUR_TOP}/' + actual_path(root, target['dir']) + '")', '']
        native_modules[name] = {'sources': module_sources, 'includes': module_includes,
                                'defines': target['defines'], 'unresolved_includes': unresolved,
                                'pending_sources': pending_sources}
        if name == 'framework':
            native_modules[name]['compiled_application_sources'] = application_sources
        if name == 'display':
            native_modules[name]['compiled_application_sources'] = application_display
    metal_manifest = output / 'display2_macos_speed.json'
    subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'),
                    '--top', str(root), '--root', 'code/mercury/library/graphics/display2/jamfile.jam',
                    '--target', 'MACOS', '--platform', 'MACOS', '--build', 'Speed',
                    '--out', str(metal_manifest)], check=True, cwd=root)
    display2 = next(t for t in json.loads(metal_manifest.read_text())['targets'] if t['name'] == 'display2')
    shared_display2 = [actual_path(root, p) for p in display2['sources'] if any(p.lower().endswith(suffix)
        for suffix in ('/context/context.cpp','/device/basedevice.cpp','/device/device.cpp','/display2logger.cpp','/utils/utils.cpp','/memory/memory.cpp','/buffer/buffer.cpp'))]
    metal_sources = [actual_path(root, p) for p in display2['sources'] if '/metal/' in p.lower()]
    if not metal_sources:
        raise ValueError('Native Display2 Metal sources missing from Jam')
    lines += ['set(BLUR_MAC_DISPLAY2_METAL_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in metal_sources + shared_display2]
    lines += [')', '']
    native_modules['display2_metal'] = {'sources': metal_sources, 'compiled_shared_sources': shared_display2,
        'pending_sources': [actual_path(root, p) for p in display2['sources'] if '/metal/' not in p.lower() and actual_path(root,p) not in shared_display2]}
    framework_manifest = output / 'framework_macos_speed.json'
    subprocess.run([sys.executable, str(root / 'tools/jam2cmake/jamextract.py'), '--top', str(root),
        '--root', 'code/mercury/library/gamesys/framework/jamfile.jam', '--target', 'MACOS', '--platform', 'MACOS',
        '--build', 'Speed', '--out', str(framework_manifest)], check=True, cwd=root)
    framework_mac = next(t for t in json.loads(framework_manifest.read_text())['targets'] if t['name']=='framework')
    window_sources = [actual_path(root,p) for p in framework_mac['sources'] if '/macos/' in p.lower() and Path(p).name.lower()=='macwindow.mm']
    if not window_sources: raise ValueError('Native framework host missing from Jam')
    lines += ['set(BLUR_MAC_FRAMEWORK_NATIVE_SOURCES', *[f'    "${{BLUR_TOP}}/{p}"' for p in window_sources], ')', '']
    native_modules['framework_macos'] = {'sources': window_sources}
    application_native_sources = [actual_path(root,p) for p in framework_mac['sources'] if '/macos/' in p.lower() and Path(p).name.lower()!='macwindow.mm']
    if not application_native_sources:raise ValueError('Native framework application missing from Jam')
    lines += ['set(BLUR_MAC_APPLICATION_NATIVE_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in application_native_sources]
    lines += [')','']
    native_modules['framework_application_macos'] = {'sources':application_native_sources}
    audio_manifest = output / 'audio_macos_speed.json'
    subprocess.run([sys.executable,str(root / 'tools/jam2cmake/jamextract.py'),'--top',str(root),
        '--root','code/mercury/library/audio/jamfile.jam','--target','MACOS','--platform','MACOS',
        '--build','Speed','--out',str(audio_manifest)],check=True,cwd=root)
    audio_mac = next(t for t in json.loads(audio_manifest.read_text())['targets'] if t['name']=='audio')
    audio_sources = [actual_path(root,p) for p in audio_mac['sources'] if p.lower().endswith('/macos/sdlplayback.cpp')]
    audio_engine = [actual_path(root,p) for p in audio_mac['sources'] if '/macos/' in p.lower() and not p.lower().endswith('/macos/sdlplayback.cpp')]
    if not audio_sources:raise ValueError('Native SDL audio output missing from Jam')
    lines += ['set(BLUR_MAC_AUDIO_NATIVE_SOURCES']
    lines += [f'    "${{BLUR_TOP}}/{p}"' for p in audio_sources]
    lines += [')','']
    audio_vendor = [actual_path(root,p) for p in audio_mac['sources'] if '/soundtouch/' in p.lower()]
    audio_original = [actual_path(root,p) for p in audio_mac['sources'] if '/macos/' not in p.lower() and '/soundtouch/' not in p.lower()]
    lines += ['set(BLUR_MAC_AUDIO_ENGINE_NATIVE_SOURCES', *[f'    "${{BLUR_TOP}}/{p}"' for p in audio_engine], ')','']
    lines += ['set(BLUR_MAC_AUDIO_ORIGINAL_SOURCES', *[f'    "${{BLUR_TOP}}/{p}"' for p in audio_original], ')','']
    lines += ['set(BLUR_MAC_AUDIO_INCLUDE_DIRS', *[f'    "${{BLUR_TOP}}/{actual_path(root,p["path"])}"' for p in audio_mac['includes'] if p['exists']], ')','']
    native_modules['audio'] = {'sources':audio_sources,'engine_native_sources':audio_engine,'compiled_original_sources':audio_original,'replaced_vendor_sources':audio_vendor,'pending_sources':[]}
    lines += ['set(BLUR_MAC_SHADER_TARGETS']
    lines += ['    "' + t['name'] + '"' for t in targets if t['shaders']]
    lines += [')', '']
    (output / 'mac_sources.cmake').write_text('\n'.join(lines))
    (output / 'mac_source_inventory.json').write_text(json.dumps({
        'compiled_original_core': sources,
        'compiled_native_core': native_core,
        'replaced_platform_core': replaced,
        'upstream_core_count': len(core['sources']),
        'compiled_original_system': system_sources,
        'compiled_engine_system': pending_system,
        'native_modules': native_modules,
        'target_inventory': {t['name']: len(t['sources']) for t in targets},
    }, indent=2) + '\n')
    print(f"macOS core: {len(sources)} original sources, {len(replaced)} platform replacements")


if __name__ == '__main__':
    main()
